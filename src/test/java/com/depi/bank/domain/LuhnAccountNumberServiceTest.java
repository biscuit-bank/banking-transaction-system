package com.depi.bank.domain;

import org.junit.jupiter.api.BeforeEach;
import org.junit.jupiter.api.DisplayName;
import org.junit.jupiter.api.Test;
import org.junit.jupiter.params.ParameterizedTest;
import org.junit.jupiter.params.provider.ValueSource;

import static org.junit.jupiter.api.Assertions.*;

class LuhnAccountNumberServiceTest {

    private LuhnAccountNumberService service;

    @BeforeEach
    void setUp() {
        service = new LuhnAccountNumberService();
    }

    @Test
    @DisplayName("Positive Test: Valid 12-digit Luhn numbers should pass validation")
    void testValidAccountNumbers() {
        // Valid 12-digit Luhn numbers
        assertTrue(service.isValid("799273987138"));
        assertTrue(service.isValid("123456789015"));
        // Legacy numbers generated by the previous check-digit convention remain accepted
        assertTrue(service.isValid("799273987130"));
        assertTrue(service.isValid("123456789012"));
    }

    @ParameterizedTest
    @ValueSource(strings = {
        "799273987131", // Incorrect check digit
        "123456789011", // Off-by-one check digit
        "12345678901",   // 11 digits (too short)
        "1234567890123", // 13 digits (too long)
        "12345678901A", // Non-numeric character
        "",             // Empty string
    })
    @DisplayName("Negative Test: Invalid numbers/formats should fail validation")
    void testInvalidAccountNumbers(String invalidNumber) {
        assertFalse(service.isValid(invalidNumber));
    }

    @Test
    @DisplayName("Negative Test: Null input should return false gracefully")
    void testNullInput() {
        assertFalse(service.isValid(null));
    }

    @Test
    @DisplayName("Deterministic Generation Test: Same seed produces identical valid account number")
    void testDeterministicGeneration() {
        long seed = 42L;

        String gen1 = service.generateDeterministic(seed);
        String gen2 = service.generateDeterministic(seed);

        assertEquals(gen1, gen2, "Generated account numbers with same seed should be equal");
        assertEquals(12, gen1.length(), "Generated account number must be 12 digits long");
        assertTrue(service.isValid(gen1), "Generated account number must be Luhn valid");
    }

    @Test
    @DisplayName("Check Digit Calculation Test: 11-digit payload returns correct check digit")
    void testCalculateCheckDigit() {
        String payload = "79927398713";
        int checkDigit = service.calculateCheckDigit(payload);
        
        assertEquals(8, checkDigit);
        assertTrue(service.isValid(payload + checkDigit));
    }

    @Test
    @DisplayName("DOM-01: 1,000 generated account numbers are unique, 12 digits, and Luhn valid")
    void testGeneratedAccountNumbersAreUniqueAndValid() {
        java.util.Set<String> generated = new java.util.HashSet<>();

        for (long seed = 0; seed < 1000; seed++) {
            String accountNumber = service.generateDeterministic(seed);
            assertEquals(12, accountNumber.length());
            assertTrue(service.isValid(accountNumber));
            generated.add(accountNumber);
        }

        assertEquals(1000, generated.size(), "Generated account numbers must be unique");
    }
}
